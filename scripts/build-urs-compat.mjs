// Assemble urs-compat.js from its two parts:
//   region `jquery` — jQuery 1.7.2, the exact version the legacy engine handed
//                     the URS scripts, turned into `uf$` with noConflict(true);
//   region `urs`    — urs-compat.src.js, the engine itself.
// Run after editing urs-compat.src.js:  node scripts/build-urs-compat.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const jq = readFileSync(join(ROOT, 'vendor/jquery-1.7.2.min.js'), 'utf8').replace(/^\/\*![\s\S]*?\*\/\s*/, '').trim();
const src = readFileSync(join(ROOT, 'urs-compat.src.js'), 'utf8').trim();
// The IDE prop translation, shared with the converter (window.U1Ide._translate).
const ide = readFileSync(join(ROOT, 'ide-convert.js'), 'utf8').trim();
const out =
  `/* GENERATED by scripts/build-urs-compat.mjs — edit urs-compat.src.js, not this file. */\n` +
  `//#region u1-engine:jquery\n${jq}\nwindow.uf$ = jQuery.noConflict(true);\n//#endregion\n` +
  `//#region u1-engine:ide\n${ide}\n//#endregion\n` +
  `//#region u1-engine:urs\n${src}\n//#endregion\n`;
writeFileSync(join(ROOT, 'urs-compat.js'), out);
console.log(`urs-compat.js: ${out.length} bytes (jquery ${jq.length}, ide translate ${ide.length}, engine ${src.length})`);

// ── Guard: the panel strips comments from this engine before export, with a
// scanner that knows strings but not regex literals. A quote or `//` inside a
// regex has cut the shipped file twice. Re-run that exact stripper here and
// require the token stream (acorn) to be identical before and after — so a
// stripped engine can only ever lose comments.
{
  const acorn = (() => { const m = { exports: {} }; new Function('module', 'exports', 'define', readFileSync(join(ROOT, 'vendor/acorn.js'), 'utf8'))(m, m.exports, undefined); return m.exports; })();
  const panel = readFileSync(join(ROOT, 'panel.js'), 'utf8');
  const a = panel.indexOf('function stripComments(');
  let i = panel.indexOf('{', a), d = 0;
  for (; i < panel.length; i++) { const c = panel[i]; if (c === '{') d++; else if (c === '}') { if (--d === 0) { i++; break; } } else if (c === '"' || c === "'" || c === '`') { const q = c; for (i++; i < panel.length; i++) { if (panel[i] === '\\') { i++; continue; } if (panel[i] === q) break; } } }
  const stripComments = new Function('return ' + panel.slice(a, i))();
  const tokens = (code) => { const t = []; for (const tok of acorn.tokenizer(code, { ecmaVersion: 'latest' })) t.push(tok.type.label + ':' + (tok.value === undefined ? '' : String(tok.value))); return t; };
  for (const [name, code] of [['ide-convert.js', ide], ['urs-compat.src.js', src]]) {
    const before = tokens(code), after = tokens(stripComments(code));
    const at = before.findIndex((t, k) => t !== after[k]);
    if (at > -1 || before.length !== after.length) {
      console.error(`Build aborted: stripping comments changes ${name} (first difference at token ${at}: ${before[at]} → ${after[at]}). A regex literal there contains a quote or "//"; write those characters as \\x27 \\x22 \\x60 \\/ escapes.`);
      process.exit(1);
    }
  }
  console.log('comment stripping verified: token streams identical');
}
